/// Viewport configuration
#[pyclass]
#[derive(Debug, Clone, Copy, Serialize, Deserialize)]
pub struct Viewport {
    #[pyo3(get, set)]
    pub width: u32,
    #[pyo3(get, set)]
    pub height: u32,
    #[pyo3(get, set)]
    pub device_scale_factor: f64,
    #[pyo3(get, set)]
    pub is_mobile: bool,
}

#[pymethods]
impl Viewport {
    #[new]
    pub fn new(width: u32, height: u32) -> Self {
        Self {
            width,
            height,
            device_scale_factor: 1.0,
            is_mobile: width < 768,
        }
    }

    #[staticmethod]
    pub fn mobile() -> Self {
        Self::new(375, 812)
    }

    #[staticmethod]
    pub fn tablet() -> Self {
        Self::new(768, 1024)
    }

    #[staticmethod]
    pub fn desktop() -> Self {
        Self::new(1440, 900)
    }
}

/// Complete captured page with all data
#[pyclass]
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct CapturedPage {
    /// Source URL
    #[pyo3(get, set)]
    pub url: String,

    /// Page title
    #[pyo3(get, set)]
    pub title: Option<String>,

    /// Viewport used for capture
    #[pyo3(get)]
    pub viewport: Viewport,

    /// All captured elements (keyed by ID)
    pub elements: HashMap<String, CapturedElement>,

    /// Root element ID
    #[pyo3(get, set)]
    pub root_id: Option<String>,

    /// All CSS rules (deduplicated)
    pub css_rules: Vec<CssRule>,

    /// Media queries
    pub media_queries: Vec<MediaQuery>,

    /// Keyframe animations
    pub keyframes: Vec<Keyframes>,

    /// CSS variables
    pub css_variables: Vec<CssVariable>,

    /// Font faces
    pub font_faces: Vec<FontFace>,

    /// Raw HTML (cleaned)
    #[pyo3(get, set)]
    pub html: String,

    /// Generated unified CSS
    #[pyo3(get, set)]
    pub css: String,

    /// Screenshot (base64 PNG)
    #[pyo3(get, set)]
    pub screenshot: Option<String>,

    /// Capture timestamp
    #[pyo3(get, set)]
    pub timestamp: String,
}

#[pymethods]
impl CapturedPage {
    #[new]
    pub fn new(url: String, viewport: Viewport) -> Self {
        Self {
            url,
            title: None,
            viewport,
            elements: HashMap::new(),
            root_id: None,
            css_rules: Vec::new(),
            media_queries: Vec::new(),
            keyframes: Vec::new(),
            css_variables: Vec::new(),
            font_faces: Vec::new(),
            html: String::new(),
            css: String::new(),
            screenshot: None,
            timestamp: chrono_now(),
        }
    }

    pub fn get_element(&self, id: &str) -> Option<CapturedElement> {
        self.elements.get(id).cloned()
    }

    pub fn element_count(&self) -> usize {
        self.elements.len()
    }

    pub fn rule_count(&self) -> usize {
        self.css_rules.len()
    }
}

fn chrono_now() -> String {
    // Simple timestamp without chrono dependency
    "2026-01-27T00:00:00Z".to_string()
}

/// Configuration for capture process
#[pyclass]
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct CaptureConfig {
    /// Viewports to capture
    #[pyo3(get, set)]
    pub viewports: Vec<Viewport>,

    /// Whether to capture hover states
    #[pyo3(get, set)]
    pub capture_hover: bool,

    /// Whether to capture focus states
    #[pyo3(get, set)]
    pub capture_focus: bool,

    /// Whether to capture active states
    #[pyo3(get, set)]
    pub capture_active: bool,

    /// Whether to capture pseudo-elements
    #[pyo3(get, set)]
    pub capture_pseudo_elements: bool,

    /// Whether to take screenshots
    #[pyo3(get, set)]
    pub take_screenshots: bool,

    /// Whether to download fonts
    #[pyo3(get, set)]
    pub download_fonts: bool,

    /// Whether to download images
    #[pyo3(get, set)]
    pub download_images: bool,

    /// Maximum elements to process (0 = unlimited)
    #[pyo3(get, set)]
    pub max_elements: usize,

    /// Timeout in milliseconds
    #[pyo3(get, set)]
    pub timeout_ms: u64,

    /// User agent string
    #[pyo3(get, set)]
    pub user_agent: Option<String>,
}

#[pymethods]
impl CaptureConfig {
    #[new]
    pub fn new() -> Self {
        Self::default()
    }

    #[staticmethod]
    pub fn full() -> Self {
        Self {
            viewports: vec![
                Viewport::mobile(),
                Viewport::tablet(),
                Viewport::desktop(),
            ],
            capture_hover: true,
            capture_focus: true,
            capture_active: true,
            capture_pseudo_elements: true,
            take_screenshots: true,
            download_fonts: false,
            download_images: false,
            max_elements: 0,
            timeout_ms: 30000,
            user_agent: None,
        }
    }

    #[staticmethod]
    pub fn fast() -> Self {
        Self {
            viewports: vec![Viewport::desktop()],
            capture_hover: false,
            capture_focus: false,
            capture_active: false,
            capture_pseudo_elements: false,
            take_screenshots: false,
            download_fonts: false,
            download_images: false,
            max_elements: 500,
            timeout_ms: 15000,
            user_agent: None,
        }
    }
}

impl Default for CaptureConfig {
    fn default() -> Self {
        Self {
            viewports: vec![Viewport::desktop()],
            capture_hover: true,
            capture_focus: true,
            capture_active: false,
            capture_pseudo_elements: true,
            take_screenshots: true,
            download_fonts: false,
            download_images: false,
            max_elements: 1000,
            timeout_ms: 30000,
            user_agent: None,
        }
    }
}
