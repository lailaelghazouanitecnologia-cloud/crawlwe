/// Computed CSS styles for an element in a specific state
#[pyclass]
#[derive(Debug, Clone, Serialize, Deserialize, Default)]
pub struct ComputedStyles {
    /// All CSS properties and their computed values
    #[pyo3(get, set)]
    pub properties: HashMap<String, String>,
}

#[pymethods]
impl ComputedStyles {
    #[new]
    pub fn new() -> Self {
        Self::default()
    }

    pub fn get(&self, property: &str) -> Option<String> {
        self.properties.get(property).cloned()
    }

    pub fn set(&mut self, property: String, value: String) {
        self.properties.insert(property, value);
    }

    pub fn len(&self) -> usize {
        self.properties.len()
    }

    pub fn is_empty(&self) -> bool {
        self.properties.is_empty()
    }

    pub fn keys(&self) -> Vec<String> {
        self.properties.keys().cloned().collect()
    }
}

/// CSS specificity (a, b, c) where:
/// a = ID selectors
/// b = class selectors, attributes, pseudo-classes
/// c = type selectors, pseudo-elements
#[pyclass]
#[derive(Debug, Clone, Copy, Serialize, Deserialize, Default, PartialEq, Eq, PartialOrd, Ord)]
pub struct Specificity {
    #[pyo3(get, set)]
    pub ids: u32,
    #[pyo3(get, set)]
    pub classes: u32,
    #[pyo3(get, set)]
    pub elements: u32,
}

#[pymethods]
impl Specificity {
    #[new]
    pub fn new(ids: u32, classes: u32, elements: u32) -> Self {
        Self { ids, classes, elements }
    }

    fn __str__(&self) -> String {
        format!("({}, {}, {})", self.ids, self.classes, self.elements)
    }

    fn __repr__(&self) -> String {
        format!("Specificity({}, {}, {})", self.ids, self.classes, self.elements)
    }
}

/// Source of a CSS rule
#[derive(Debug, Clone, Serialize, Deserialize)]
pub enum StyleSource {
    /// External stylesheet file
    External { url: String },
    /// Inline <style> tag
    InlineStyle { index: usize },
    /// Inline style attribute
    StyleAttribute,
    /// Generated by JavaScript
    JavaScript,
    /// User agent stylesheet
    UserAgent,
}

/// A CSS rule with its origin and specificity
#[pyclass]
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct CssRule {
    #[pyo3(get, set)]
    pub selector: String,
    #[pyo3(get, set)]
    pub declarations: HashMap<String, String>,
    #[pyo3(get)]
    pub specificity: Specificity,
    #[pyo3(get, set)]
    pub source_file: Option<String>,
    #[pyo3(get, set)]
    pub line: Option<usize>,
}

#[pymethods]
impl CssRule {
    #[new]
    pub fn new(selector: String) -> Self {
        Self {
            selector,
            declarations: HashMap::new(),
            specificity: Specificity::default(),
            source_file: None,
            line: None,
        }
    }

    pub fn add_declaration(&mut self, property: String, value: String) {
        self.declarations.insert(property, value);
    }

    pub fn to_css_string(&self) -> String {
        let declarations: Vec<String> = self
            .declarations
            .iter()
            .map(|(k, v)| format!("  {}: {};", k, v))
            .collect();
        format!("{} {{\n{}\n}}", self.selector, declarations.join("\n"))
    }
}

/// A captured DOM element with all its states
#[pyclass]
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct CapturedElement {
    /// Unique identifier for this element
    #[pyo3(get, set)]
    pub id: String,

    /// HTML tag name (lowercase)
    #[pyo3(get, set)]
    pub tag: String,

    /// Element's ID attribute if present
    #[pyo3(get, set)]
    pub element_id: Option<String>,

    /// CSS classes
    #[pyo3(get, set)]
    pub classes: Vec<String>,

    /// Other attributes (excluding id, class, style)
    #[pyo3(get, set)]
    pub attributes: HashMap<String, String>,

    /// Text content (direct text, not from children)
    #[pyo3(get, set)]
    pub text_content: Option<String>,

    /// Computed styles for each CSS state
    pub styles_by_state: HashMap<String, ComputedStyles>,

    /// Box model dimensions
    #[pyo3(get)]
    pub box_model: BoxModel,

    /// Parent element ID
    #[pyo3(get, set)]
    pub parent_id: Option<String>,

    /// Children element IDs (ordered)
    #[pyo3(get, set)]
    pub children_ids: Vec<String>,

    /// CSS rules that match this element
    pub matched_rules: Vec<CssRule>,

    /// Depth in DOM tree (0 = root)
    #[pyo3(get, set)]
    pub depth: usize,
}

#[pymethods]
impl CapturedElement {
    #[new]
    pub fn new(id: String, tag: String) -> Self {
        Self {
            id,
            tag,
            element_id: None,
            classes: Vec::new(),
            attributes: HashMap::new(),
            text_content: None,
            styles_by_state: HashMap::new(),
            box_model: BoxModel::default(),
            parent_id: None,
            children_ids: Vec::new(),
            matched_rules: Vec::new(),
            depth: 0,
        }
    }

    pub fn get_styles(&self, state: &str) -> Option<ComputedStyles> {
        self.styles_by_state.get(state).cloned()
    }

    pub fn set_styles(&mut self, state: String, styles: ComputedStyles) {
        self.styles_by_state.insert(state, styles);
    }

    pub fn has_state(&self, state: &str) -> bool {
        self.styles_by_state.contains_key(state)
    }

    pub fn states(&self) -> Vec<String> {
        self.styles_by_state.keys().cloned().collect()
    }

    pub fn class_string(&self) -> String {
        self.classes.join(" ")
    }
}

