//! Core data models for CrawlWe
//!
//! These structures represent the captured state of a web page,
//! including all CSS states, computed styles, and DOM structure.

use pyo3::prelude::*;
use serde::{Deserialize, Serialize};
use std::collections::HashMap;

/// Represents a CSS pseudo-state
#[pyclass]
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq, Hash)]
pub enum CssState {
    Base,
    Hover,
    Focus,
    FocusVisible,
    FocusWithin,
    Active,
    Visited,
    Checked,
    Disabled,
    Empty,
    FirstChild,
    LastChild,
    Before,
    After,
    Placeholder,
    Selection,
}

#[pymethods]
impl CssState {
    fn __str__(&self) -> &'static str {
        match self {
            CssState::Base => "base",
            CssState::Hover => "hover",
            CssState::Focus => "focus",
            CssState::FocusVisible => "focus-visible",
            CssState::FocusWithin => "focus-within",
            CssState::Active => "active",
            CssState::Visited => "visited",
            CssState::Checked => "checked",
            CssState::Disabled => "disabled",
            CssState::Empty => "empty",
            CssState::FirstChild => "first-child",
            CssState::LastChild => "last-child",
            CssState::Before => "before",
            CssState::After => "after",
            CssState::Placeholder => "placeholder",
            CssState::Selection => "selection",
        }
    }
}

